const OUT_DIR = "public/audio";
if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });

const speak = async (text, file) => {
  const res = await fetch("https://ai.gateway.lovable.dev/v1/audio/speech", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: "google/gemini-2.5-flash-tts",
      contents: [
        {
          role: "user",
          parts: [
            {
              text: `Read this in a warm, calm, professional narrator voice at a measured pace: ${text}`,
            },
          ],
        },
      ],
      generationConfig: {
        responseModalities: ["AUDIO"],
        speechConfig: {
          voiceConfig: { prebuiltVoiceConfig: { voiceName: VOICE } },
        },
      },
    }),
  });
  if (!res.ok) {
    throw new Error(`TTS failed [${res.status}]: ${await res.text()}`);
  }
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(file, buf);
  const dur = Number(
    execFileSync("ffprobe", [
      "-v",
      "error",
      "-show_entries",
      "format=duration",
      "-of",
      "default=nw=1:nk=1",
      file,
    ])
      .toString()
      .trim(),
  );
  return dur;
};

const LEAD = 14;
const GAP = 22;
const TAIL = 26;
const plan = [];
const scenes = [];

for (const scene of SCENES) {
  let cursor = LEAD;
  const lines = [];
  for (let i = 0; i < scene.lines.length; i++) {
    const file = `${OUT_DIR}/${scene.id}-${i}.wav`;
    const dur = await speak(scene.lines[i], file);
    const frames = Math.ceil(dur * FPS);
    lines.push({
      from: cursor,
      duration: frames + GAP,
      text: scene.lines[i],
      file: `${scene.id}-${i}.wav`,
    });
    cursor += frames + GAP;
    console.log(scene.id, i, dur.toFixed(2) + "s");
  }
  scenes.push({ id: scene.id, duration: cursor + TAIL, lines });
}

// absolute offsets with 20-frame transition overlaps
const T = 20;
let start = 0;
scenes.forEach((s, i) => {
  s.start = i === 0 ? 0 : start;
  s.lines.forEach((l) => {
    plan.push({ file: l.file, atSeconds: (s.start + l.from) / FPS });
  });
  start = s.start + s.duration - T;
});
const total = scenes[scenes.length - 1].start + scenes[scenes.length - 1].duration;

writeFileSync(
  "src/narration.ts",
  `// Generated by scripts/generate-narration.mjs — do not edit by hand.
export const TRANSITION = ${T};
export const TOTAL_FRAMES = ${total};
export const SCENES: Record<
  string,
  { duration: number; lines: { from: number; duration: number; text: string }[] }
> = ${JSON.stringify(
    Object.fromEntries(
      scenes.map((s) => [
        s.id,
        {
          duration: s.duration,
          lines: s.lines.map(({ from, duration, text }) => ({
            from,
            duration,
            text,
          })),
        },
      ]),
    ),
    null,
    2,
  )};
export const ORDER = ${JSON.stringify(scenes.map((s) => s.id))};
`,
);
writeFileSync("/tmp/audio_plan.json", JSON.stringify({ plan, total }, null, 2));
